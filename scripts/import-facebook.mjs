/**
 * One-off import of the pictures pulled down from the centre's Facebook page.
 *
 *   <folder>/<year>/<facebook-id>.jpg  ->  public/media/facebook/**  +  data/facebook-seed.sql
 *
 * Everything becomes a gallery piece filed under its folder's year, with no
 * title or artist — Facebook gives us neither, and the committee will tidy or
 * remove pieces through the admin. The pictures ship as static assets like the
 * WordPress archive did, because this is a single batch: anything added from
 * now on goes through the admin and into R2.
 *
 * The seed only ever INSERTs, so it is safe to run against a database that
 * already has content. Re-running the script rebuilds its own folder and file.
 *
 *   node scripts/import-facebook.mjs [C:/Users/me/Pictures/rosebankpic]
 */
import { readdir, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const SOURCE = process.argv[2] ?? 'C:/Users/94304/Pictures/rosebankpic';
const OUT_DIR = 'public/media/facebook';
const SEED = 'data/facebook-seed.sql';
const FULL_EDGE = 2400;
const THUMB_EDGE = 600;

/** Hamming distance between two 64-bit dHashes at or under this is the same picture. */
const NEAR_DUPLICATE = 6;

const sqlStr = (v) =>
  v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

/* -- duplicate detection --------------------------------------------------
   Facebook hands the same photograph back at more than one size, and the same
   picture gets posted to more than one album. A difference hash on a 9x8
   greyscale thumbnail catches both: it survives resizing and recompression
   but changes as soon as the picture actually differs.                     */

async function dHash(file) {
  const px = await sharp(file)
    .rotate()
    .grayscale()
    .resize(9, 8, { fit: 'fill' })
    .raw()
    .toBuffer();
  const bits = [];
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      bits.push(px[y * 9 + x] < px[y * 9 + x + 1] ? 1 : 0);
    }
  }
  return bits;
}

const hamming = (a, b) => a.reduce((n, bit, i) => n + (bit ^ b[i]), 0);

/* -- main ------------------------------------------------------------------ */

async function main() {
  const years = (await readdir(SOURCE, { withFileTypes: true }))
    .filter((d) => d.isDirectory() && /^\d{4}$/.test(d.name))
    .map((d) => d.name)
    .sort();

  // Every candidate, with enough about it to pick the best of any duplicates.
  const candidates = [];
  for (const year of years) {
    const dir = path.join(SOURCE, year);
    const files = (await readdir(dir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f));
    for (const file of files) {
      const source = path.join(dir, file);
      const fbid = file.replace(/\.[a-z]+$/i, '');
      const meta = await sharp(source).metadata();
      candidates.push({
        year,
        fbid,
        source,
        pixels: (meta.width ?? 0) * (meta.height ?? 0),
        hash: await dHash(source),
      });
    }
  }

  // Facebook's ids climb over time, so within a year they are roughly the
  // order the pictures were posted in.
  candidates.sort((a, b) => a.year.localeCompare(b.year) || (a.fbid < b.fbid ? -1 : 1));

  const kept = [];
  const dropped = [];
  for (const c of candidates) {
    const twin = kept.find((k) => hamming(k.hash, c.hash) <= NEAR_DUPLICATE);
    if (!twin) {
      kept.push(c);
    } else if (c.pixels > twin.pixels) {
      // Keep the larger copy but the earlier slot, so ordering is unaffected.
      dropped.push({ ...twin, twin: c });
      Object.assign(twin, c);
    } else {
      dropped.push({ ...c, twin });
    }
  }

  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  const now = Math.floor(Date.now() / 1000);
  const lines = [
    '-- Generated by scripts/import-facebook.mjs. Do not edit by hand.',
    '-- Additive only: safe to run against a database that already has content.',
    '',
  ];

  const positions = new Map();
  for (const c of kept) {
    const id = `fb-${c.fbid}`;
    const fullName = `${id}-full.webp`;
    const thumbName = `${id}-thumb.webp`;

    const full = await sharp(c.source)
      .rotate()
      .resize({ width: FULL_EDGE, height: FULL_EDGE, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 82 })
      .toFile(path.join(OUT_DIR, fullName));

    await sharp(c.source)
      .rotate()
      .resize({ width: THUMB_EDGE, height: THUMB_EDGE, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(path.join(OUT_DIR, thumbName));

    const position = positions.get(c.year) ?? 0;
    positions.set(c.year, position + 1);

    lines.push(
      `INSERT OR IGNORE INTO images (id, key_full, key_thumb, width, height, alt, source_url, created_at) VALUES (` +
        `${sqlStr(id)}, ${sqlStr(`media/facebook/${fullName}`)}, ${sqlStr(`media/facebook/${thumbName}`)}, ` +
        `${full.width}, ${full.height}, '', ${sqlStr(`https://www.facebook.com/photo/?fbid=${c.fbid}`)}, ${now});`,
      `INSERT OR IGNORE INTO artworks (id, image_id, title, artist, year, medium, event_id, featured, position, status, created_at) VALUES (` +
        `${sqlStr(`art-${id}`)}, ${sqlStr(id)}, '', '', ${sqlStr(c.year)}, NULL, NULL, 0, ${position}, 'published', ${now});`,
    );
    process.stdout.write(`  ${c.year}  ${c.fbid}  ${full.width}x${full.height}\n`);
  }

  await writeFile(SEED, lines.join('\n') + '\n');

  console.log(`
--- facebook import summary --------------------------------
  pictures found     ${candidates.length}
  duplicates dropped ${dropped.length}`);
  for (const d of dropped) console.log(`    ${d.year}/${d.fbid}  (same as ${d.twin.year}/${d.twin.fbid})`);
  console.log(`  pieces imported    ${kept.length}  (${[...positions].map(([y, n]) => `${y}: ${n}`).join(', ')})
  images written to  ${OUT_DIR}
  seed written to    ${SEED}
-----------------------------------------------------------`);
}

main();
